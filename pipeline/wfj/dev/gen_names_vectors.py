"""Generate vectors/names_vectors.{jsonl,lua}: the shared contract between core/names.py and Core/Names.lua.

Each row: {id, text, it, en}: `text` resolved to the Italian (`it`) and to the English (`en`) form of every
marked name (spec §8). Both suites iterate every row.
Usage: python -m wfj.dev.gen_names_vectors [out_dir]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from wfj.core import names
from wfj.emit.lua_writer import lua_string

CASES: list[tuple[str, str]] = [
    ("plain", "Porta queste pelli al fabbro."),
    ("one", "Porta queste pelli a ⟦Stormwind City=Roccavento⟧."),
    ("two", "Da ⟦Goldshire=Borgodoro⟧ a ⟦Stormwind City=Roccavento⟧, poi ⟦Ironforge=Forgiardente⟧."),
    ("digits", "Vai al ⟦Sector 7G=Settore 7G⟧ e torna con 7 casse."),
    ("apostrophe", "Hai visto il ⟦Sharptalon's Claw=Artiglio di Sharptalon⟧ all'⟦Alliance=Alleanza⟧?"),
    ("placeholders",
     "{name}, porta $N1 ⟦Linen Cloth=Tessuto di Lino⟧ a ⟦Stormwind City=Roccavento⟧.\n\nGrazie."),
    ("accents", "La ⟦Thousand Needles=Millepicchi⟧ è più a sud di ⟦Mulgore=Mulgore⟧."),
    ("adjacent", "⟦Horde=Orda⟧⟦Alliance=Alleanza⟧"),
    ("broken", "Un ⟦ senza chiusura e un = solo."),
    ("escape", "|cffffd100⟦Hogger=Hogger⟧|r e |Hitem:1|h[⟦Linen Cloth=Tessuto di Lino⟧]|h"),
    # style "en": "The " goes after an Italian article or articulated preposition, never elsewhere
    ("the_article", "Difendi la ⟦The Bulwark=Il Baluardo⟧ e il ⟦The Great Sea=Mare Infinito⟧."),
    ("the_capital", "Il ⟦The Great Sea=Mare Infinito⟧ è vasto. Nelle ⟦The Barrens=Savane⟧ fa caldo."),
    ("the_elided", "Torna dall'⟦The Den=Antro del Tirocinio⟧ e nell’⟦The Den=Antro del Tirocinio⟧."),
    ("the_kept",
     "Vai verso ⟦The Barrens=Savane⟧, poi Isola ⟦The Barrens=Savane⟧; ⟦The Den=Antro del Tirocinio⟧."),
]


def build() -> list[dict]:
    return [
        {"id": i, "text": t, "it": names.resolve(t, "it"), "en": names.resolve(t, "en")} for i, t in CASES
    ]


def to_lua(rows: list[dict]) -> str:
    lines = [
        "-- GENERATED by pipeline/wfj/dev/gen_names_vectors.py from names_vectors.jsonl. Do not edit.",
        "return { cases = {",
    ]
    for r in rows:
        lines.append(
            f"  {{ id = {lua_string(r['id'])}, text = {lua_string(r['text'])}, it = {lua_string(r['it'])}, "
            f"en = {lua_string(r['en'])} }},"
        )
    lines.append("} }")
    return "\n".join(lines) + "\n"


def write(out_dir: Path) -> None:
    rows = build()
    out_dir.mkdir(parents=True, exist_ok=True)
    with (out_dir / "names_vectors.jsonl").open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    (out_dir / "names_vectors.lua").write_text(to_lua(rows), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    out = Path(args[0]) if args else Path(__file__).resolve().parents[3] / "vectors"
    write(out)
    print(f"wrote {out / 'names_vectors.jsonl'} + .lua ({len(CASES)} cases)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
