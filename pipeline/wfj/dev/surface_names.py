"""`make surface-names`: addon/…/Names from the retail itIT tables (Blizzard's Italian names).

The addon keeps no English: a row's key is the hash of the name the client shows (Core/Hash, UI/NameText).
Two Italian names for one English: the most common; a tie ships nothing, the client's English stays.
"""
from __future__ import annotations

import argparse
import csv
import itertools
import re
from collections import Counter, defaultdict
from pathlib import Path

from wfj.core.hashing import key
from wfj.core.normalize import normalize_v1
from wfj.dev.glossary_it import TABLES as _TABLES
from wfj.dev.glossary_it import _column, _forever_english
from wfj.io import retail
from wfj.io.jsonl_store import Store

ROOT = Path(__file__).resolve().parents[3]
KINDS = {"oggetto": "NameItem", "abilita": "NameSpell", "zona": "NameZone", "fazione": "NameFaction"}
TABLES = {kind: _TABLES[kind] for kind in KINDS}
# internal rows, never a name a player reads
JUNK = re.compile(r"\[|\]|\(DND\)|\(OLD\)|\bUNUSED\b|\bDEPRECATED\b|^zz|^Monster - |^Test |\bTEST\b"
                  r"|^PLAYER,|^NPC ")


def collect(rows):
    """rows: (kind, english, italian). → {kind: {english: italian}}"""
    forms = defaultdict(lambda: defaultdict(Counter))
    for kind, en, it in rows:
        usable = en and it and en != it and not (set(en + it) & set("\t\n\r"))
        if kind in KINDS and usable and not JUNK.search(en) and not JUNK.search(it):
            forms[kind][en][it] += 1
    out = {}
    for kind, names in forms.items():
        out[kind] = {}
        for en, counts in names.items():
            top = counts.most_common(2)
            if len(top) == 1 or top[0][1] > top[1][1]:
                out[kind][en] = top[0][0]
    return out


def lua_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua_file(type_: str, names: dict[str, str]) -> str:
    rows = sorted((key(normalize_v1(en)), it) for en, it in names.items())
    head = ("-- GENERATED by `make surface-names` from the retail itIT tables. Do not edit.\n"
            f'local _, WFJ = ...\nWFJ.Data.add("{type_}", {{\n')
    body = "".join(f'  ["{k}"] = {{ {lua_string(it)}, "." }},\n' for k, it in rows)
    return head + body + "})\n"


def retail_rows(retail_dir: Path, forever_dir: Path, store: Store):
    """(kind, english, italian) for every id with Forever's English. Unlike the glossary, one-word names
    stay: the glossary finds names in sentences, here the whole text is the name."""
    for kind, (table, en_col, it_cols) in TABLES.items():
        forever = _forever_english(kind, store, forever_dir)
        english = _column(retail.csv_path(retail_dir, table, "enUS"), "ID", [en_col])
        italian = _column(retail.csv_path(retail_dir, table, "itIT"), "ID", it_cols)
        for id_, (en,) in english.items():
            if id_ in italian and forever is not None and forever.get(id_) == en:
                yield kind, en, italian[id_][0]
    # the skills panel's lines: Forever has no name table of its own for them
    english = _column(retail.csv_path(retail_dir, "SkillLine", "enUS"), "ID", ["DisplayName_lang"])
    italian = _column(retail.csv_path(retail_dir, "SkillLine", "itIT"), "ID", ["DisplayName_lang"])
    for id_, (en,) in english.items():
        if id_ in italian:
            yield "abilita", en, italian[id_][0]


def curated_rows():
    """The project's own names for zones and factions, for what the id match above leaves out."""
    for name in ("glossario_ufficiale.tsv", "glossario_curato.tsv"):
        with (ROOT / "pipeline" / name).open(encoding="utf-8", newline="") as f:
            for row in csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE):
                if row["tipo"] in ("zona", "fazione"):
                    yield row["tipo"], row["en"], row["it"]


COINED = "nomi_coniati.tsv"


def coined_rows(path: Path | None = None):
    """`pipeline/nomi_coniati.tsv` (`tipo\\ten\\tit\\tnota`): Italian names for the objects and spells Forever
    added, which no Italian client has (the camping system: `Basic Campfire` → `Fuoco da Campo Semplice`).
    Names only, never glossary terms: they are common nouns (`Anvil`, `Loom`) that would mark the inside of
    longer English names (`Burning Anvil`). A row of another kind, or with no English or no Italian, is
    refused."""
    path = path or ROOT / "pipeline" / COINED
    with path.open(encoding="utf-8", newline="") as f:
        for n, row in enumerate(csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE), 2):
            if row.get("tipo") not in ("oggetto", "abilita") or not (row.get("en") or "").strip() \
                    or not (row.get("it") or "").strip():
                raise ValueError(f"{path.name}:{n}: not `oggetto|abilita\\ten\\tit\\tnota`: {row!r}")
            yield row["tipo"], row["en"], row["it"]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--retail", type=Path, required=True)
    parser.add_argument("--forever", type=Path, required=True)
    args = parser.parse_args()
    store = Store(ROOT / "data", english=True)
    rows = itertools.chain(retail_rows(args.retail, args.forever, store), curated_rows(), coined_rows())
    names = collect(rows)
    out = ROOT / "addon" / "OldpZ_ForeverITA" / "Names"
    out.mkdir(exist_ok=True)
    for kind, file in KINDS.items():
        (out / f"{file}.lua").write_bytes(lua_file(file.lower(), names[kind]).encode("utf-8"))
        print(f"{file}: {len(names[kind])}")


if __name__ == "__main__":
    main()
